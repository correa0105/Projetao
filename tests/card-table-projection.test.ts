import {test} from 'node:test';
import assert from 'node:assert/strict';
import {cardTableCardCorners,cardTableLayouts,cardTableMatrix,cardTableNativeMatrix,cardTableProjection,cardTableScenes,projectTablePoint} from '../src/card-table-projection';

function crossing(a:{x:number;y:number},b:{x:number;y:number},c:{x:number;y:number},d:{x:number;y:number}) {
  const dx=b.x-a.x,dy=b.y-a.y,ex=d.x-c.x,ey=d.y-c.y,det=dx*ey-dy*ex;
  const t=((c.x-a.x)*ey-(c.y-a.y)*ex)/det;return {x:a.x+t*dx,y:a.y+t*dy};
}

test('the native plane passes through the four actual mat corners, including its wooden back strip',()=>{
  for(const kind of ['wide','tall'] as const){
    const scene=cardTableScenes[kind],size=cardTableLayouts[kind],matrix=cardTableNativeMatrix(kind);
    for(const [i,[x,y]] of [[0,size.matTop],[size.width,size.matTop],[size.width,size.height],[0,size.height]].entries()){
      const point=projectTablePoint(matrix,x,y),expected=scene.points[i];
      assert(Math.abs(point.x-expected.x)<1e-6);assert(Math.abs(point.y-expected.y)<1e-6);
    }
  }
});
test('card depth edges converge with independently measured leather seams instead of the old inner rectangle',()=>{
  // Linear fits to untouched background pixels, not points generated by the
  // projection. Each pair samples the visible left/right mat seam.
  const seams={
    wide:[[{x:383.0063,y:600},{x:301.1983,y:660}],[{x:1338.6356,y:600},{x:1413.9059,y:660}]],
    tall:[[{x:261.3401,y:825},{x:161.9653,y:955}],[{x:875.1114,y:825},{x:956.8372,y:955}]],
  };
  for(const kind of ['wide','tall'] as const){
    const [left,right]=seams[kind],vanishing=crossing(left[0],left[1],right[0],right[1]),matrix=cardTableNativeMatrix(kind);
    for(let i=0;i<3;i++){
      const q=cardTableCardCorners(kind,i).map(c=>projectTablePoint(matrix,c.x,c.y));
      for(const [a,b] of [[q[0],q[3]],[q[1],q[2]]]){
        const x=b.x-a.x,y=b.y-a.y,vx=vanishing.x-a.x,vy=vanishing.y-a.y;
        const sine=Math.abs(x*vy-y*vx)/(Math.hypot(x,y)*Math.hypot(vx,vy));
        assert(sine<.0003,kind+' card edge misses photographed vanishing point');
      }
    }
  }
});
test('cards retain readable depth and fit the viewport without fitting the entire cropped background',()=>{
  for(const [width,height] of [[1920,1080],[1440,900],[1280,720],[974,600],[768,1024],[390,844],[320,740],[320,922],[1920,720]]){
    const p=cardTableProjection(width,height),q=cardTableCardCorners(p.kind,1).map(c=>projectTablePoint(p.matrix,c.x,c.y));
    const ratio=Math.hypot(q[3].x-q[0].x,q[3].y-q[0].y)/Math.hypot(q[1].x-q[0].x,q[1].y-q[0].y);
    assert(p.kind==='wide'?ratio>.52&&ratio<.7:ratio>1.15&&ratio<1.6,'Card depth collapsed at '+width);
    for(let i=0;i<3;i++)for(const corner of cardTableCardCorners(p.kind,i)){
      const point=projectTablePoint(p.matrix,corner.x,corner.y);
      assert(point.x>=9.99&&point.x<=width-9.99);assert(point.y>=9.99&&point.y<=height-9.99);
    }
    if(width>=1280||width===390)assert.equal(p.factor,1,'Off-screen scenery must not shrink visible cards');
  }
});
