export const crestArtLayers = ['banner', 'frame', 'symbol'] as const;
export function crestArtImageSource(kind: 'cloth' | 'sigils' | 'ornaments', index: number) {
  const ids = kind === 'cloth' ? crestArtBanners : kind === 'sigils' ? crestArtSigils : crestArtFrames;
  const expanded = crestExpansion.find((x) => x.id === ids[index]);
  return expanded?.image ?? '/guild/crests-20261019/' + kind + '-' + (index + 1) + '.webp';
}
export const crestArtSchema = z
  .object({
    banner: z.enum(crestArtBanners).default('swallowtail'),
    symbol: z.enum(crestArtSigils).default('phoenix-relief'),
    frame: z.enum(crestArtFrames).default('elven-leaves'),
    order: z
      .array(z.enum(crestArtLayers))
      .length(3)
      .default(() => ['banner', 'frame', 'symbol'] as Array<(typeof crestArtLayers)[number]>)
      .refine((v) => new Set(v).size === 3, 'Camadas repetidas.'),
    showBanner: z.boolean().default(true),
    showFrame: z.boolean().default(true),
    showSymbol: z.boolean().default(true),
    symbolScale: z.number().finite().min(0.5).max(1.5).default(1),
    symbolX: z.number().finite().min(-25).max(25).default(0),
    symbolY: z.number().finite().min(-25).max(25).default(0),
    symbolRotation: z.number().finite().min(-180).max(180).default(0),
  })
  .strict();
export type CrestArt = z.infer<typeof crestArtSchema>;
