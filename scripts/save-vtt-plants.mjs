import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
const [id,source]=process.argv.slice(2);
const plan=JSON.parse(await fs.readFile('data/vtt/plants-plan-20261014.json','utf8'));
const asset=plan.assets.find(a=>a.id===id);
if(!asset||!source)throw Error('Expected a planned plant ID and generated PNG.');
const bytes=await fs.readFile(source),meta=await sharp(bytes).metadata(),stats=await sharp(bytes).stats();
if(!meta.hasAlpha||stats.isOpaque)throw Error('A plant needs genuine transparent alpha.');
const directory='public/vtt/plants-20261014',sources='data/vtt/plants-sources-20261014',records='data/vtt/plants-completed-20261014';
for(const folder of [directory,sources,records])await fs.mkdir(folder,{recursive:true});
await fs.writeFile(path.join(sources,id+'.png'),bytes);
const output=await sharp(bytes).trim().resize({width:764,height:764,fit:'inside'}).extend({top:2,bottom:2,left:2,right:2,background:{r:0,g:0,b:0,alpha:0}}).webp({quality:94}).toBuffer();
const exported=await sharp(output).metadata(),longest=Math.max(exported.width,exported.height);
const record={...asset,image:'/vtt/plants-20261014/'+id+'.webp',width:Number((asset.squares*exported.width/longest).toFixed(4)),height:Number((asset.squares*exported.height/longest).toFixed(4)),pixelWidth:exported.width,pixelHeight:exported.height,source:sources+'/'+id+'.png',sourceSha256:createHash('sha256').update(bytes).digest('hex'),sha256:createHash('sha256').update(output).digest('hex'),tool:'built-in image_gen'};
await fs.writeFile(path.join(directory,id+'.webp'),output);
await fs.writeFile(path.join(records,id+'.json'),JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify({id,width:exported.width,height:exported.height,saved:true}));
